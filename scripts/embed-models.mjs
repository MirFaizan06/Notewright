// Packs trained network JSON files into core/models.js (weights as base64 float32).
// usage: node scripts/embed-models.mjs onset.json offset.json [refine.json [pre.json]]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'core', 'models.js');
const b64 = (arr) => Buffer.from(Float32Array.from(arr).buffer).toString('base64');
const pack = (file) => {
  const j = JSON.parse(fs.readFileSync(file, 'utf8'));
  return `{
  sizes: ${JSON.stringify(j.sizes)},
  threshold: ${(+j.threshold).toFixed(4)},
  mean: '${b64(j.mean)}',
  std: '${b64(j.std)}',
  W: [${j.W.map((w) => `'${b64(w)}'`).join(',\n    ')}],
  B: [${j.B.map((b) => `'${b64(b)}'`).join(',\n    ')}],
}`;
};
const [onset, offset, refine, pre] = process.argv.slice(2);
const body = `// Generated by scripts/embed-models.mjs from trained weights. Do not edit by hand.

const f32 = (s) => {
  const bin = atob(s);
  const u8 = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) u8[i] = bin.charCodeAt(i);
  return new Float32Array(u8.buffer);
};
const unpack = (m) => ({
  sizes: m.sizes, threshold: m.threshold,
  mean: f32(m.mean), std: f32(m.std),
  W: m.W.map(f32), B: m.B.map(f32),
});

export const ONSET_NET = unpack(${pack(onset)});

export const OFFSET_NET = ${offset ? `unpack(${pack(offset)})` : 'null'};

export const REFINE_NET = ${refine ? `unpack(${pack(refine)})` : 'null'};

// cheap first filter: its threshold is a logit cut-off, not a probability
export const PRE_NET = ${pre ? `unpack(${pack(pre)})` : 'null'};
`;
fs.writeFileSync(out, body);
console.log('wrote', out, (body.length / 1024).toFixed(0) + ' KB');
